    clean = sum(1 for r in rows if r["label"] == "none")
    print(f"\n{len(rows)} rows ({clean} clean, {len(rows)-clean} corrupted) "
          f"-> {save_to}")
    if failures:
        print(f"FAILED: {failures}  (re-run to retry; cache keeps the rest)")
    return rows


